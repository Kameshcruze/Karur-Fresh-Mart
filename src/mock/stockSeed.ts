export function formatPackAndUnit(packSize: string, unit?: string): string {
  const cleanPack = packSize.trim();
  const cleanUnit = (unit ?? '').trim();
  if (!cleanPack) return cleanUnit || '1 pack';
  if (!cleanUnit) return cleanPack;
  if (cleanPack.toLowerCase().endsWith(cleanUnit.toLowerCase())) {
    return cleanPack;
  }
  return `${cleanPack} ${cleanUnit}`;
}

export function splitPackAndUnit(packSizeLabel: string, explicitUnit?: string): {
  packSize: string;
  unit: string;
} {
  const clean = packSizeLabel.trim();
  if (explicitUnit && explicitUnit.trim()) {
    const u = explicitUnit.trim();
    const regex = new RegExp(`\\s*${u.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')}$`, 'i');
    return {
      packSize: clean.replace(regex, '').trim() || clean,
      unit: u,
    };
  }
  const match = clean.match(/^(.+?)\s+([a-zA-Z]+)$/);
  if (match) {
    return { packSize: match[1].trim(), unit: match[2].trim() };
  }
  return { packSize: clean || '1', unit: 'pack' };
}

export function seedDefinitionToProduct(def: StockSeedDefinition): Product {
  const matchedBrand = MOCK_BRANDS.find((b) => b.id === def.brandId);
  const matchedCat = MOCK_CATEGORIES.find((c) => c.id === def.categoryId);
  return {
    id: def.productId,
    sku: def.item_code,
    name: {
      en: def.product_name,
      ta: def.product_name_tamil,
    },
    brandId: matchedBrand?.id ?? def.brandId,
    categoryId: matchedCat?.id ?? def.categoryId,
    packSize: formatPackAndUnit(def.pack_size, def.unit),
    unit: def.unit,
    price: def.selling_price,
    mrp: def.mrp,
    stockQty: def.stock_qty,
    reservedQty: def.reservedQty,
    lowStockThreshold: def.low_stock_threshold,
    imageTint: def.imageTint,
    image: def.image_url || undefined,
    description: {
      en: def.descriptionEn,
      ta: def.descriptionTa,
    },
    visibleOnline: def.visible_online === 'yes',
    isFeatured: def.isFeatured,
    rating: def.rating,
    updatedAt: '2026-11-15T08:00:00.000Z',
  };
}

